import { test, expect } from '@playwright/test';
test('local demo, alignment, comparison and real exports',async({page})=>{
 await page.goto('/');
 await expect(page.getByRole('button',{name:'PNG diff',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'Открыть демо'}).click();
 await expect(page.getByText('Демо · локально')).toBeVisible();
 await expect(page.getByTestId('stage')).toBeVisible();
 await page.getByLabel('Смещение X').fill('12');
 await page.getByLabel('Масштаб изображения').fill('110');
 await page.getByRole('button',{name:'Различия',exact:true}).click();
 await expect(page.getByTestId('mismatch')).not.toHaveText('—');
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'JSON отчёт'}).click();
 const file=await download;
 const fs=await import('node:fs/promises'); const report=JSON.parse(await fs.readFile((await file.path())!,'utf8'));
 expect(report.transform).toEqual({x:12,y:0,scale:1.1}); expect(report.comparison.totalPixels).toBe(960*640);
 const png=page.waitForEvent('download'); await page.getByRole('button',{name:'PNG diff',exact:true}).click();
 const image=await fs.readFile((await (await png).path())!); expect(image.subarray(1,4).toString()).toBe('PNG');
 await page.getByRole('button',{name:'Сбросить выравнивание'}).click();
 await expect(page.getByLabel('Смещение X')).toHaveValue('0');
 await expect(page.getByLabel('Масштаб изображения')).toHaveValue('100');
});
test('uploads, errors, drag and narrow viewport',async({page})=>{
 await page.goto('/');
 const png=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=200;c.height=100;const g=c.getContext('2d')!;g.fillStyle='red';g.fillRect(0,0,200,100);return c.toDataURL().split(',')[1];});
 await page.getByLabel('Загрузить эталон').setInputFiles({name:'reference.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
 await page.getByLabel('Загрузить реализацию').setInputFiles({name:'actual.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
 await expect(page.getByTestId('mismatch')).toHaveText('0.00%');
 const c=page.getByTestId('stage');const box=(await c.boundingBox())!;
 await page.mouse.move(box.x+20,box.y+20);await page.mouse.down();await page.mouse.move(box.x+40,box.y+30);await page.mouse.up();
 await expect(page.getByLabel('Смещение X')).toHaveValue('20');await expect(page.getByLabel('Смещение Y')).toHaveValue('10');
 await c.press('Shift+ArrowRight');await expect(page.getByLabel('Смещение X')).toHaveValue('30');
 await page.getByLabel('Загрузить реализацию').setInputFiles({name:'broken.png',mimeType:'image/png',buffer:Buffer.from('broken')});
 await expect(page.getByRole('alert')).toContainText('Не удалось прочитать');
 await page.getByLabel('Загрузить реализацию').setInputFiles({name:'no.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg/>')});
 await expect(page.getByRole('alert')).toContainText('только PNG');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:'Открыть демо'}).click();await page.screenshot({path:'test-results/screenshot-tester-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:'test-results/screenshot-tester-desktop.png',fullPage:true});
});
